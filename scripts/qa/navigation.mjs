    await page.getByLabel('Nome', { exact: true }).fill('S09 fluxo completo')
    await page.getByLabel('Endpoint autorizado').selectOption(endpoint.id)
    await page.getByLabel('Duração (s)', { exact: true }).fill('2')
    await page.getByLabel('Inicial', { exact: true }).fill('3')
    await page.getByLabel('Máxima', { exact: true }).fill('2')
    assert.equal(await page.getByRole('button', { name: 'Salvar cenário' }).isDisabled(), true)
    await shot(page, '02-validacao-concorrencia')
    await page.getByLabel('Inicial', { exact: true }).fill('1')
    await page.getByLabel('Ajuste', { exact: true }).fill('1')
    await page.getByLabel('P95 limite').fill('500')
    await page.getByLabel('Erro limite').fill('0.1')
    await page.getByLabel(/^Estratégia/).selectOption('RULES')
